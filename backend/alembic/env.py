import asyncio
import os
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import context
from app.core.config import get_settings
from app.registry import Base  # every module's models, so the metadata is complete

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

url = config.get_main_option("sqlalchemy.url") or os.environ.get("DATABASE_URL") or get_settings().database_url
target_metadata = Base.metadata


def run_migrations_offline() -> None:
    context.configure(
        url=url, target_metadata=target_metadata, literal_binds=True, dialect_opts={"paramstyle": "named"}
    )
    with context.begin_transaction():
        context.run_migrations()


def _comparing_to_models() -> bool:
    """True for `alembic revision --autogenerate` and `alembic check`.

    Only then do migrations see the models' metadata: Alembic would otherwise apply its naming
    convention to the names old migrations create, and they must keep replaying exactly as they
    first ran. New autogenerated migrations carry explicit op.f() names, and
    tests/test_migrations.py checks every name at head against the convention.
    """
    opts = config.cmd_opts
    if opts is None:
        return False
    return bool(getattr(opts, "autogenerate", False)) or getattr(opts, "cmd", (None,))[0].__name__ == "check"


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata if _comparing_to_models() else None,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = create_async_engine(url, poolclass=pool.NullPool)
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
